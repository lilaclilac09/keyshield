import { resolve } from 'node:path';
import { test, expect, installHarness, page, popup, origin, secondOrigin, samples, output, networkRequests, openPopup, unlock, add, save, selection } from './harness';

installHarness();

test('extension appearance: locked, Add key, saved key and selection confirmation', async () => {
  const directory = process.env.KEYSHIELD_STYLE_SCREENSHOTS || output;
  await openPopup();
  await popup.setViewportSize({ width: 400, height: 900 });
  await popup.locator('#lock').click();
  await expect(popup.locator('#status')).toHaveText('Vault locked');
  await expect(popup.locator('#status')).toHaveClass('status status--locked');
  await expect(popup.locator('#entry-list li')).toHaveCount(0);
  await expect(popup.locator('#fill-availability')).toHaveText('No saved key selected. Unlock or add a key.');
  await expect(popup.locator('body')).toHaveCSS('background-color', 'rgba(0, 0, 0, 0)');
  await expect(popup.locator('html')).toHaveCSS('background-color', 'rgb(11, 18, 38)');
  await popup.evaluate(() => document.fonts.ready);
  expect(await popup.evaluate(() => document.fonts.check('13px Montserrat'))).toBe(true);
  await popup.screenshot({ path: resolve(directory, 'popup-locked.png'), fullPage: true });
  await unlock();
  await popup.locator('#key-value').fill(samples[0].value);
  await popup.screenshot({ path: resolve(directory, 'popup-add-key.png'), fullPage: true });
  await add();
  await popup.locator('#label').fill('Local test key');
  await save();
  await expect(popup.locator('#entry-list .badge')).toHaveText('This device only');
  await expect(popup.locator('#entry-list .saved-key-origin')).toHaveText(`Fill only on ${origin}`);
  await expect(popup.locator('#fill-availability')).toHaveText(`Fill only on ${origin}`);
  await expect(popup.locator('#status')).toHaveClass('status status--success');
  await popup.screenshot({ path: resolve(directory, 'popup-saved-key.png'), fullPage: true });
  await popup.close();
  await selection('input');
  await popup.setViewportSize({ width: 400, height: 900 });
  await expect(popup.locator('#confirmation')).toBeVisible();
  await expect(popup.locator('.storage-note')).toHaveText('Saved to: this device only (encrypted extension vault — not the dashboard/Device Vault)');
  await expect(popup.locator('.binding')).toHaveText(`Can fill on: ${origin}`);
  await popup.screenshot({ path: resolve(directory, 'confirmation.png'), fullPage: true });
  await popup.close();
  await page.goto(`${secondOrigin}/input.html`);
  await page.locator('input').fill('');
  await page.locator('input').focus();
  await openPopup();
  await popup.setViewportSize({ width: 400, height: 900 });
  await expect(popup.locator('#fill-availability')).toHaveText(`Not available on this site. Fill only on ${origin}`);
  await popup.locator('#fill').click();
  await expect(popup.locator('#status')).toHaveText('Fill refused: this key belongs to another origin');
  await expect(popup.locator('#status')).toHaveClass('status status--error');
  await expect(page.locator('input')).toHaveValue('');
  await popup.screenshot({ path: resolve(directory, 'popup-other-approved-origin.png'), fullPage: true });
  expect(networkRequests.filter((request) => /^https?:/.test(request.url)).every((request) => [new URL(origin).hostname, new URL(secondOrigin).hostname].includes(new URL(request.url).hostname))).toBe(true);
});
