"""ZK mode (zk-v1): the server stores provider keys it cannot read.

Opt-in per user. Spec: docs/zk/ZK-MODE.md. Summary:

  root R   = HKDF-SHA256(passkey PRF output, info="keyshield/zk/v1/root")
             derived on the user's device; never sent here.
  share S  = 32 random bytes per item, generated by the client and kept
             ONLY here (zk_shares). Useless without R.
  item key = HKDF-SHA256(ikm=R, salt=S, info="keyshield/zk/v1/item:<id>:<upstream>")
  cipher   = AES-256-GCM(item key, iv, provider key, aad="<id>|<upstream>")

The server keeps cipher + iv + S. Decryption needs R (user's devices) and
S (released here to a valid token for that user). Revoking a token stops
the release of S, which is how revocation reaches a local proxy.

Kill switch: KS_ZK_DISABLED=1 turns every /zk route into 404 and makes
/manage/store refuse cipher_v=2 rows.
"""

from __future__ import annotations

import base64
import os
import re
import time

from fastapi import APIRouter, Request
from fastapi.responses import JSONResponse

router = APIRouter()

ZK_CIPHER_V = 2
_B64URL = re.compile(r"^[A-Za-z0-9_-]+$")
_ROOT_ID = re.compile(r"^[A-Za-z0-9_-]{16,64}$")
_HINT = re.compile(r"^[A-Za-z0-9_-]{0,16}$")


def zk_disabled() -> bool:
    return os.environ.get("KS_ZK_DISABLED", "").strip() == "1"


def ensure_tables(conn) -> None:
    conn.execute(
        """
        CREATE TABLE IF NOT EXISTS zk_users (
            user_id    TEXT PRIMARY KEY,
            root_id    TEXT NOT NULL,
            enabled_at REAL NOT NULL
        )
        """
    )
    conn.execute(
        """
        CREATE TABLE IF NOT EXISTS zk_shares (
            item_id    TEXT NOT NULL,
            user_id    TEXT NOT NULL,
            share      TEXT NOT NULL,
            created_at REAL NOT NULL,
            PRIMARY KEY (item_id, user_id)
        )
        """
    )


def user_zk(conn, user_id: str) -> dict | None:
    ensure_tables(conn)
    row = conn.execute(
        "SELECT root_id, enabled_at FROM zk_users WHERE user_id = ?", (user_id,)
    ).fetchone()
    if not row:
        return None
    return {"root_id": row[0], "enabled_at": row[1]}


def _b64_len(value: str, n: int | None = None, max_len: int = 8192) -> bytes | None:
    if not isinstance(value, str) or not value or len(value) > max_len:
        return None
    if not _B64URL.match(value):
        return None
    try:
        raw = base64.urlsafe_b64decode(value + "=" * (-len(value) % 4))
    except Exception:
        return None
    if n is not None and len(raw) != n:
        return None
    return raw


def validate_zk_body(body: dict) -> tuple[dict | None, str | None]:
    """Check a cipher_v=2 store body. Returns (fields, error)."""
    if str(body.get("value") or body.get("apiKey") or body.get("api_key") or "").strip():
        return None, "zk rows must not carry a plaintext value"
    cipher = body.get("cipher")
    iv = body.get("iv")
    share = body.get("share")
    if _b64_len(cipher) is None or len(_b64_len(cipher) or b"") < 17:
        return None, "cipher must be base64url AES-GCM output"
    if _b64_len(iv, 12) is None:
        return None, "iv must be 12 bytes base64url"
    if _b64_len(share, 32) is None:
        return None, "share must be 32 bytes base64url"
    item_id = str(body.get("id") or "")
    if not re.match(r"^ks_[a-f0-9]{12,32}$", item_id):
        return None, "zk rows need a client-chosen id (ks_<hex>), it is bound into the AAD"
    hint = str(body.get("hint") or "")
    if not _HINT.match(hint):
        return None, "hint must be a short public prefix such as sk-proj-"
    return {"cipher": cipher, "iv": iv, "share": share, "id": item_id, "hint": hint}, None


def _session(request: Request) -> dict | None:
    from ..auth import session as sess_mod

    raw = request.headers.get("Authorization", "")
    if not raw.startswith("Bearer "):
        return None
    return sess_mod.get(raw[7:])


def _gate(request: Request, owner: bool = False):
    from ..auth import session as sess_mod

    if zk_disabled():
        return None, JSONResponse({"detail": "Not Found"}, status_code=404)
    sess = _session(request)
    if not sess:
        return None, JSONResponse({"error": "invalid token"}, status_code=401)
    if owner and not sess_mod.is_owner(sess):
        return None, JSONResponse({"error": "insufficient_scope"}, status_code=403)
    return sess, None


@router.get("/zk/status")
async def zk_status(request: Request):
    from .vault import _db

    sess, err = _gate(request)
    if err:
        return err
    with _db() as conn:
        info = user_zk(conn, sess["user_id"])
        plaintext = conn.execute(
            "SELECT COUNT(*) FROM vault_items WHERE user_id = ? AND TRIM(value) != ''",
            (sess["user_id"],),
        ).fetchone()[0]
        zk_items = conn.execute(
            "SELECT COUNT(*) FROM vault_items WHERE user_id = ? AND cipher_v = ?",
            (sess["user_id"], ZK_CIPHER_V),
        ).fetchone()[0]
    return JSONResponse(
        {
            "enabled": bool(info),
            "root_id": (info or {}).get("root_id"),
            "plaintext_items": int(plaintext),
            "zk_items": int(zk_items),
            "version": "zk-v1",
        }
    )


@router.post("/zk/enable")
async def zk_enable(request: Request):
    """Turn on ZK mode. Body: {root_id}. root_id is a fingerprint of R."""
    from .vault import _db

    sess, err = _gate(request, owner=True)
    if err:
        return err
    try:
        body = await request.json()
    except Exception:
        body = {}
    root_id = str((body or {}).get("root_id") or "")
    if not _ROOT_ID.match(root_id):
        return JSONResponse({"detail": "root_id (base64url fingerprint) required"}, status_code=400)
    with _db() as conn:
        current = user_zk(conn, sess["user_id"])
        if current and current["root_id"] != root_id:
            return JSONResponse(
                {
                    "error": "root_mismatch",
                    "detail": "ZK mode is already on with a different passkey root.",
                },
                status_code=409,
            )
        if not current:
            conn.execute(
                "INSERT INTO zk_users (user_id, root_id, enabled_at) VALUES (?, ?, ?)",
                (sess["user_id"], root_id, time.time()),
            )
    return JSONResponse({"ok": True, "root_id": root_id})


@router.post("/zk/disable")
async def zk_disable(request: Request):
    """Turn ZK mode off. Existing zk rows stay (and stay unreadable here)."""
    from .vault import _db

    sess, err = _gate(request, owner=True)
    if err:
        return err
    with _db() as conn:
        ensure_tables(conn)
        conn.execute("DELETE FROM zk_users WHERE user_id = ?", (sess["user_id"],))
    return JSONResponse({"ok": True})


@router.get("/zk/items")
async def zk_items(request: Request):
    """Ciphertext rows for this user. Safe for proxy tokens: no shares here."""
    from .vault import _db

    sess, err = _gate(request)
    if err:
        return err
    with _db() as conn:
        rows = conn.execute(
            "SELECT id, name, upstream, cipher, iv, tags, created_at, updated_at "
            "FROM vault_items WHERE user_id = ? AND cipher_v = ? ORDER BY created_at DESC",
            (sess["user_id"], ZK_CIPHER_V),
        ).fetchall()
    out = [
        {
            "id": r[0],
            "name": r[1],
            "upstream": r[2],
            "cipher": r[3],
            "iv": r[4],
            "cipher_v": ZK_CIPHER_V,
            "created_at": r[6],
            "updated_at": r[7],
        }
        for r in rows
    ]
    return JSONResponse({"items": out, "version": "zk-v1"})


@router.get("/zk/share/{item_id}")
async def zk_share(item_id: str, request: Request):
    """Release the server share S for one item to a valid token of its owner.

    This is the revocation point: a revoked or expired token gets 401 here,
    so a local proxy can no longer derive the item key once its short share
    cache runs out.
    """
    from .vault import _db

    sess, err = _gate(request)
    if err:
        return err
    with _db() as conn:
        ensure_tables(conn)
        row = conn.execute(
            "SELECT share FROM zk_shares WHERE item_id = ? AND user_id = ?",
            (item_id, sess["user_id"]),
        ).fetchone()
    if not row:
        return JSONResponse({"detail": "item not found"}, status_code=404)
    resp = JSONResponse({"id": item_id, "share": row[0], "max_cache_seconds": 60})
    resp.headers["Cache-Control"] = "no-store"
    return resp


@router.post("/zk/purge-plaintext")
async def zk_purge_plaintext(request: Request):
    """Delete every plaintext row for this user and compact the DB file.

    Run after re-saving keys in ZK mode. Only removes rows that still hold
    a plaintext value; zk rows are untouched. Backups/snapshots of the DB
    made before this call are outside its reach (see migration notes).
    """
    from .vault import _db

    sess, err = _gate(request, owner=True)
    if err:
        return err
    with _db() as conn:
        cur = conn.execute(
            "DELETE FROM vault_items WHERE user_id = ? AND TRIM(value) != ''",
            (sess["user_id"],),
        )
        deleted = int(cur.rowcount or 0)
        conn.commit()
        conn.execute("PRAGMA wal_checkpoint(TRUNCATE)")
    # VACUUM can't run inside a transaction; use a fresh connection.
    import sqlite3

    from .vault import _DB_PATH

    vc = sqlite3.connect(str(_DB_PATH), isolation_level=None)
    try:
        vc.execute("PRAGMA secure_delete = ON")
        vc.execute("VACUUM")
    finally:
        vc.close()
    return JSONResponse({"ok": True, "deleted": deleted})
